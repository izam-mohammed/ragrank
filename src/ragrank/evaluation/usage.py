"""Token and cost accounting for an evaluation run.

Every metric call goes through a language model, and until now the token
counts those models report were collected and thrown away. "This eval
cost me forty dollars and I don't know why" is a real complaint, and the
data to answer it was already in hand.
"""

from __future__ import annotations

from threading import Lock

from ragrank.bridge.pydantic import BaseModel, ConfigDict, Field
from ragrank.llm.base import BaseLLM, LLMResult


class TokenUsage(BaseModel):
    """Tokens consumed by an evaluation run.

    Attributes:
        prompt_tokens (int): Tokens sent to the model.
        response_tokens (int): Tokens generated by the model.
        calls (int): Number of model calls made.
        unreported_calls (int): Calls where the provider gave no usage,
            so the totals above are a lower bound.
    """

    model_config: ConfigDict = ConfigDict(frozen=True)

    prompt_tokens: int = Field(default=0, ge=0)
    response_tokens: int = Field(default=0, ge=0)
    calls: int = Field(default=0, ge=0)
    unreported_calls: int = Field(default=0, ge=0)

    @property
    def total_tokens(self) -> int:
        """Prompt and response tokens combined.

        Returns:
            int: The total.
        """
        return self.prompt_tokens + self.response_tokens

    @property
    def is_complete(self) -> bool:
        """Whether every call reported its usage.

        Returns:
            bool: False if any call is missing usage, which makes the
                totals a lower bound rather than an answer.
        """
        return self.unreported_calls == 0

    def cost(
        self,
        *,
        per_prompt_token: float,
        per_response_token: float,
    ) -> float:
        """Estimate the spend at the given rates.

        Rates are per single token, so a price of $5 per million input
        tokens is `5 / 1e6`.

        Args:
            per_prompt_token (float): Price of one prompt token.
            per_response_token (float): Price of one response token.

        Returns:
            float: The estimated cost.
        """
        return (
            self.prompt_tokens * per_prompt_token
            + self.response_tokens * per_response_token
        )

    def __add__(self, other: TokenUsage) -> TokenUsage:
        """Combine two usage records.

        Args:
            other (TokenUsage): The record to add.

        Returns:
            TokenUsage: The combined usage.
        """
        return TokenUsage(
            prompt_tokens=self.prompt_tokens + other.prompt_tokens,
            response_tokens=self.response_tokens
            + other.response_tokens,
            calls=self.calls + other.calls,
            unreported_calls=self.unreported_calls
            + other.unreported_calls,
        )

    def __repr__(self) -> str:
        """Readable summary.

        Returns:
            str: The summary.
        """
        text = (
            f"{self.calls} calls, {self.total_tokens:,} tokens "
            f"({self.prompt_tokens:,} in / {self.response_tokens:,} out)"
        )
        if not self.is_complete:
            text += f", {self.unreported_calls} without usage data"
        return text

    def __str__(self) -> str:
        """Readable summary.

        Returns:
            str: The summary.
        """
        return self.__repr__()


class UsageTracker:
    """Accumulates token usage across concurrent metric calls."""

    def __init__(self) -> None:
        """Start an empty tracker."""
        self._lock = Lock()
        self._prompt = 0
        self._response = 0
        self._calls = 0
        self._unreported = 0

    def record(self, result: LLMResult) -> None:
        """Add one model call to the running totals.

        Args:
            result (LLMResult): The result to account for.
        """
        with self._lock:
            self._calls += 1
            if (
                result.prompt_tokens is None
                and result.response_tokens is None
            ):
                self._unreported += 1
                return
            self._prompt += result.prompt_tokens or 0
            self._response += result.response_tokens or 0

    def usage(self) -> TokenUsage:
        """Snapshot the totals so far.

        Returns:
            TokenUsage: The accumulated usage.
        """
        with self._lock:
            return TokenUsage(
                prompt_tokens=self._prompt,
                response_tokens=self._response,
                calls=self._calls,
                unreported_calls=self._unreported,
            )


class TrackedLLM(BaseLLM):
    """Delegates to another LLM, recording every call it makes.

    The runner wraps whichever model each metric ends up using, so token
    accounting works the same whether the model came from `evaluate()`,
    from the metric itself, or from the library default.

    Attributes:
        inner (BaseLLM): The model doing the actual work.
    """

    model_config: ConfigDict = ConfigDict(
        arbitrary_types_allowed=True
    )

    inner: BaseLLM = Field(description="The wrapped language model.")
    tracker: object = Field(
        repr=False, description="The UsageTracker to record into."
    )

    @property
    def name(self) -> str:
        """The wrapped model's name.

        Returns:
            str: The name.
        """
        return self.inner.name

    def generate_text(self, text: str) -> LLMResult:
        """Delegate, then record the usage.

        Args:
            text (str): The input text.

        Returns:
            LLMResult: The wrapped model's result, unchanged.
        """
        result = self.inner.generate_text(text)
        self.tracker.record(result)
        return result
